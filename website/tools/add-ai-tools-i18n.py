def block_for(lang):
    d = COPY[lang]
    lines = ["  /* ---- Image Upscaler (/ai-tools) ---- */"]
    for k, v in d.items():
        lines.append("  %s: %s," % (json.dumps(k, ensure_ascii=False), json.dumps(v, ensure_ascii=False)))
    return "\n".join(lines) + "\n"


def main():
    here = os.path.dirname(os.path.abspath(__file__))
    root = os.path.dirname(here)
    for lang in LANGS:
        p = os.path.join(root, "assets", "js", "lang", "%s.js" % lang)
        with io.open(p, encoding="utf-8") as fh:
            s = fh.read()
        if "ai.badge" in s:
            print("skip %s (already has ai.*)" % lang)
            continue
        idx = s.rstrip().rfind("};")
        if idx < 0:
            print("!! cannot find closing brace in %s" % lang)
            sys.exit(1)
        head = s[:idx]
        tail = s[idx:]
        if not head.endswith("\n"):
            head += "\n"
        s2 = head + "\n" + block_for(lang) + tail
        with io.open(p, "w", encoding="utf-8", newline="\n") as fh:
            fh.write(s2)
        print("wrote %s (+%d keys)" % (lang, len(COPY[lang])))


if __name__ == "__main__":
    main()
