# -*- coding: utf-8 -*-
"""Batch-2 translation tooling: read the English blocks, build the table.

  python website/tools/zh_extract.py about             # list blocks + fingerprints
  python website/tools/zh_extract.py about --html      # include inner markup
  python website/tools/zh_extract.py --compile         # zh-batch2/*.txt -> zh-batch2.json
  python website/tools/zh_extract.py --compile --check # exit 1 if the JSON is stale

Why a generated JSON instead of a hand-written dict
---------------------------------------------------
The English already lives in the HTML; repeating it as a dict key would double
the file and then drift. So the tables are positional: the Nth translatable
block of a page maps to the Nth line of zh-batch2/<page>.txt.

Position breaks the moment someone edits a paragraph, which is exactly the
failure this file prevents: --compile records a fingerprint of each English
block in the JSON, and build_zh.py refuses to apply a translation whose
fingerprint no longer matches, naming the block instead of silently shifting
every sentence below it.

Authoring format for zh-batch2/<page>.txt
-----------------------------------------
One block per line. Blank lines and lines starting with "#" are skipped, so a
translator can group and comment. Inline markup allowed (it is inserted as HTML)
— keep links and <strong> that carry meaning, drop <span class="mono"> wrappers
that only carry styling.
"""

import hashlib
import json
import re
import sys
from pathlib import Path

from lxml import html as LH

sys.path.insert(0, str(Path(__file__).resolve().parent))

from build_zh import BLOCK_TAGS, SKIP_ANCESTORS, WEB, iter_blocks  # noqa: E402

TOOLS = Path(__file__).resolve().parent
SRC = TOOLS / "zh-batch2"
OUT = TOOLS / "zh-batch2.json"

PAGES = ["about", "aup", "calculator", "privacy", "whitepaper"]

FW = str.maketrans({"：": ":", "，": ",", "。": ".", "（": "(", "）": ")",
                    "；": ";", "！": "!", "？": "?", "、": ","})


def norm(s):
    return re.sub(r"\s+", " ", s).strip()


def fingerprint(text):
    return hashlib.sha1(norm(text).encode("utf-8")).hexdigest()[:10]


def inner_html(el):
    return (el.text or "") + "".join(
        LH.tostring(c, encoding="unicode") for c in el)


def dump(page, show_html, full=False):
    doc = LH.parse(str(WEB / f"{page}.html")).getroot()
    n = 0
    for el in iter_blocks(doc):
        text = norm(" ".join(el.itertext()))
        n += 1
        body = text if full else text[:150]
        print(f"{n - 1:>3}  {el.tag:<4} fp={fingerprint(text)}  {body}")
        if show_html and len(el):
            h = norm(inner_html(el))
            print(f"      html: {h if full else h[:220]}")
    print(f"# {page}: {n} blocks")


def read_lines(page):
    path = SRC / f"{page}.txt"
    if not path.exists():
        return None
    out = []
    for raw in path.read_text(encoding="utf-8").splitlines():
        line = raw.rstrip()
        if not line.strip() or line.lstrip().startswith("#"):
            continue
        out.append(line.strip())
    return out


def compile_tables():
    data = {"_note": "Generated by website/tools/zh_extract.py --compile. Edit zh-batch2/*.txt instead."}
    problems = []
    for page in PAGES:
        lines = read_lines(page)
        if lines is None:
            continue
        doc = LH.parse(str(WEB / f"{page}.html")).getroot()
        blocks = [norm(" ".join(el.itertext())) for el in iter_blocks(doc)]
        if len(lines) != len(blocks):
            problems.append(f"{page}: {len(blocks)} blocks in HTML, {len(lines)} lines in .txt")
            # Name the first place they diverge — the whole list is unreadable.
            for i, (a, b) in enumerate(zip(blocks, lines)):
                if fingerprint(a) != fingerprint(b) and b not in a:
                    problems.append(f"  first mismatch at #{i}: block={a[:70]!r}")
                    break
            continue
        # A line with no Chinese in it is allowed only when it *is* the English
        # block (a number, a brand, a ticker). Otherwise it is either a missed
        # translation or a skipped line — and a skipped line shifts every
        # translation below it, which is the failure this whole file guards.
        for i, (en, zh) in enumerate(zip(blocks, lines)):
            plain = norm(re.sub(r"<[^>]+>", "", zh))
            # Punctuation is not translation: a re-typed citation differs from
            # the English only in ，and 。, and that is the correct rendering of
            # an English title quoted inside a Chinese sentence.
            # Whitespace too: Chinese does not put a space after ，or 。, so a
            # citation re-typed with those marks differs only in spacing.
            same = re.sub(r"\s+", "", plain.translate(FW)) == re.sub(r"\s+", "", en.translate(FW))
            if not re.search(r"[\u4e00-\u9fff]", plain) and not same:
                problems.append(f"{page} #{i}: line has no Chinese and does not match the block\n"
                                f"    en: {en[:80]!r}\n    zh: {plain[:80]!r}")
                break
        data[page] = {"blocks": lines, "fp": [fingerprint(b) for b in blocks]}
    return data, problems


def main(argv):
    if "--compile" in argv:
        data, problems = compile_tables()
        if problems:
            for p in problems:
                print(p)
            return 1
        text = json.dumps(data, ensure_ascii=False, indent=1) + "\n"
        if "--check" in argv:
            old = OUT.read_text(encoding="utf-8") if OUT.exists() else ""
            if old != text:
                print("zh-batch2.json is stale (run: python website/tools/zh_extract.py --compile)")
                return 1
            print("zh-batch2.json is current")
            return 0
        OUT.write_text(text, encoding="utf-8")
        pages = [k for k in data if not k.startswith("_")]
        print(f"wrote {OUT.relative_to(WEB.parent)} — {len(pages)} pages")
        return 0

    args = [a for a in argv if not a.startswith("--")]
    if not args:
        print(__doc__)
        return 0
    for page in args:
        dump(page, "--html" in argv, "--full" in argv)
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
