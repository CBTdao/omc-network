#!/usr/bin/env node
/**
 * Guards for the entity graph.
 *
 * "OMC" is the Federal Open Market Committee everywhere in English finance
 * writing, so a retriever that only ever saw the three letters has no reason to
 * connect them to 泛宇宙算力, and no reason to treat the same logo on 47 URLs as
 * one organisation. The fix is two fields: an @id shared by every page, and an
 * alternateName carrying both names. These tests read the committed HTML, so a
 * page that loses either one fails here instead of being silently re-written by
 * the next build.
 */

import assert from "node:assert/strict";
import { readFileSync, readdirSync, statSync, existsSync } from "node:fs";
import { join, relative } from "node:path";
import { test } from "node:test";

const ROOT = new URL("..", import.meta.url).pathname.replace(/^\/([A-Za-z]:)/, "$1");
const WEB = ROOT + "website";
const ORG_ID = "https://omc.network/#organization";

function* walk(dir) {
  for (const name of readdirSync(dir)) {
    const p = join(dir, name);
    if (statSync(p).isDirectory()) {
      if (name === "node_modules") continue;
      yield* walk(p);
    } else if (name.endsWith(".html")) {
      yield p;
    }
  }
}

/** Every JSON-LD block on a page, parsed. */
function ldBlocks(html) {
  const out = [];
  for (const m of html.matchAll(/<script type="application\/ld\+json">([\s\S]*?)<\/script>/g)) {
    try {
      out.push(JSON.parse(m[1]));
    } catch {
      // A block that does not parse is another test's problem; skip it so this
      // one reports what it actually measures.
    }
  }
  return out;
}

/** Every Organization object anywhere in a block, nested ones included. */
function orgNodes(node, out = []) {
  if (Array.isArray(node)) {
    for (const v of node) orgNodes(v, out);
  } else if (node && typeof node === "object") {
    const kind = node["@type"];
    const kinds = Array.isArray(kind) ? kind : [kind];
    if (kinds.includes("Organization")) out.push(node);
    for (const v of Object.values(node)) orgNodes(v, out);
  }
  return out;
}

/** Every page under website/, minus the vendored tree. */
const pages = [...walk(WEB)].map((p) => ({
  path: p,
  rel: relative(WEB, p).replace(/\\/g, "/"),
  html: readFileSync(p, "utf8"),
}));

const withOrg = pages
  .map((p) => ({ ...p, orgs: ldBlocks(p.html).flatMap((b) => orgNodes(b)) }))
  .filter((p) => p.orgs.length > 0);

test("the site actually carries Organization nodes", () => {
  // If this fails, the two tests below pass vacuously.
  assert.ok(withOrg.length > 40, `only ${withOrg.length} pages have any Organization node`);
  for (const p of withOrg) {
    assert.ok(p.orgs.length >= 1, `${p.rel}: no Organization`);
  }
});

test("every Organization node resolves to the same @id", () => {
  for (const { rel, orgs } of withOrg) {
    for (const org of orgs) {
      assert.equal(org["@id"], ORG_ID, `${rel}: Organization @id is ${JSON.stringify(org["@id"])}`);
    }
  }
});

test("every Organization node carries both names, and never only the acronym", () => {
  for (const { rel, orgs } of withOrg) {
    for (const org of orgs) {
      const alt = Array.isArray(org.alternateName) ? org.alternateName : [org.alternateName];
      assert.ok(alt.includes("OMC"), `${rel}: alternateName does not carry "OMC"`);
      // The other language's name has to be there too, otherwise the Chinese and
      // English pages still describe two entities that share a logo.
      assert.ok(
        alt.includes("泛宇宙算力") || alt.includes("Omniverse Compute"),
        `${rel}: alternateName is ${JSON.stringify(alt)}`
      );
      // "OMC" alone is the string that means something else in finance.
      assert.notEqual(org.name, "OMC", `${rel}: Organization is named only the acronym`);
      assert.ok(org.name && org.name.length > 2, `${rel}: Organization has no name`);
    }
  }
});

test("the disambiguating description is in the page's own language", () => {
  // Only the top-level node is required to carry it; a publisher nested in a
  // NewsArticle is the same entity and does not need a second copy.
  for (const { rel, rel: path, orgs } of withOrg) {
    const isZh = path.startsWith("zh/");
    const described = orgs.filter((o) => o.disambiguatingDescription);
    if (!isZh && path.includes("game/")) continue; // generated by the game builder
    assert.ok(described.length > 0, `${rel}: no disambiguatingDescription`);
    for (const org of described) {
      const text = org.disambiguatingDescription;
      if (isZh) {
        assert.match(text, /公开市场委员会/, `${rel}: Chinese page describes the entity in English`);
        assert.ok(!/Federal Open Market Committee/.test(text), `${rel}: English description on a zh page`);
      } else {
        assert.match(text, /Federal Open Market Committee/, `${rel}: English page does not disambiguate`);
        assert.ok(!/公开市场委员会/.test(text), `${rel}: Chinese description on an en page`);
      }
    }
  }
});

test("every url in the sitemap has a page that says who publishes it", () => {
  // The pages that matter are the ones a crawler can reach, and the sitemap is
  // the list of those. A page missing from here would be a page that publishes
  // facts without publishing who is behind them.
  const map = readFileSync(`${WEB}/sitemap.xml`, "utf8");
  const urls = [...map.matchAll(/<loc>([^<]+)<\/loc>/g)].map((m) => m[1]);
  assert.ok(urls.length >= 30, `sitemap has ${urls.length} urls`);
  for (const url of urls) {
    const path = new URL(url).pathname;
    // /zh is a directory, not a page: trailingSlash is false, so its index.html
    // is what /zh actually serves.
    const direct = path === "/" ? `${WEB}/index.html` : `${WEB}${path}.html`;
    const file = existsSync(direct) ? direct : `${WEB}${path}/index.html`;
    assert.ok(existsSync(file), `${url} has no file at ${file}`);
    const orgs = ldBlocks(readFileSync(file, "utf8")).flatMap((b) => orgNodes(b));
    assert.ok(orgs.length > 0, `${url} publishes no Organization`);
  }
});
